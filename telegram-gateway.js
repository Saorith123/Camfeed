// =============================================================================
// Telegram Gateway client: sends a one-time code to a phone number's Telegram app (like TrueMoney).
// https://core.telegram.org/gateway/api   (HTTPS only; credits are prepaid; failed deliveries are refunded)
// Env: TELEGRAM_GATEWAY_TOKEN (required), TELEGRAM_GATEWAY_SENDER (optional verified channel username),
//      TELEGRAM_GATEWAY_TTL (seconds the code may stay undelivered before it is refunded, 30-3600, default 300)
// =============================================================================
const BASE = 'https://gatewayapi.telegram.org/';
const token = () => String(process.env.TELEGRAM_GATEWAY_TOKEN || '').trim();
const isConfigured = () => !!token();
const ttl = () => Math.min(3600, Math.max(30, parseInt(process.env.TELEGRAM_GATEWAY_TTL || '300', 10) || 300));

function gwError(code) {
  const e = new Error('Gateway: ' + code);
  e.gwCode = String(code || 'UNKNOWN');
  return e;
}

async function call(method, params) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), 8000);
  try {
    const res = await fetch(BASE + method, {
      method: 'POST', signal: ctl.signal,
      headers: { 'Authorization': 'Bearer ' + token(), 'Content-Type': 'application/json' },
      body: JSON.stringify(params)
    });
    let data;
    try { data = await res.json(); } catch (e) { throw gwError('BAD_RESPONSE'); }
    if (!data || data.ok !== true) throw gwError(data && data.error);
    return data.result || {};
  } catch (e) {
    if (e.gwCode) throw e;
    throw gwError(e.name === 'AbortError' ? 'TIMEOUT' : 'NETWORK');
  } finally {
    clearTimeout(timer);
  }
}

// 1) is this number on Telegram? (a fee applies only if it can be reached; the next call is then free)
async function checkSendAbility(phone) {
  const r = await call('checkSendAbility', { phone_number: phone });
  if (!r.request_id) throw gwError('NO_REQUEST_ID');
  return r.request_id;
}

// 2) deliver a 6-digit code generated by Telegram
async function sendCode(phone, requestId) {
  const params = { phone_number: phone, request_id: requestId, code_length: 6, ttl: ttl() };
  if (process.env.TELEGRAM_GATEWAY_SENDER) params.sender_username = String(process.env.TELEGRAM_GATEWAY_SENDER).replace(/^@/, '');
  return call('sendVerificationMessage', params);
}

// 3) does the code the person typed match? ('code_valid' | 'code_invalid' | 'code_max_attempts_exceeded' | 'expired')
async function checkCode(requestId, code) {
  const r = await call('checkVerificationStatus', { request_id: requestId, code: String(code) });
  return r.verification_status && r.verification_status.status ? r.verification_status.status : 'unknown';
}

module.exports = { isConfigured, checkSendAbility, sendCode, checkCode, ttl };
